import { readFileSync } from "node:fs";
import { strict as assert } from "node:assert";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const root = process.cwd();
const read = p => readFileSync(join(root,p),"utf8");
const files = ["index.html","app.js","world.js","world-theme.css","sw.js","styles.css","data.js","WordMap-Offline.html"];
const source = Object.fromEntries(files.map(f=>[f,read(f)]));
for (const f of ["app.js","world.js","sw.js","data.js"]) new Function(source[f]);
const ids = [...source["index.html"].matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size,"HTML contains duplicate IDs");
const refs = [...source["app.js"].matchAll(/getElementById\(["\x27]([^"\x27]+)["\x27]\)/g)].map(m=>m[1]);
const dynamic = new Set(["parentReviewBtn","parentContinueBtn"]);
const missing = [...new Set(refs.filter(id=>!ids.includes(id)&&!dynamic.has(id)))];
assert.deepEqual(missing,[],"app.js references missing static DOM IDs");
assert.match(source["app.js"],/function countError\(\)[\s\S]*?if\(!attemptCountedThisWord\)/);
assert.match(source["app.js"],/if\(!hadErrorThisAttempt\)\{hadErrorThisAttempt=true;p\.wrong\+\+;state\.daily\.wrong\+\+;\}/);
assert.match(source["app.js"],/function refreshWordSelectors\(\)/);
assert.match(source["app.js"],/completed=false;hadErrorThisAttempt=false;attemptCountedThisWord=false/);
assert.match(source["world.js"],/document\.addEventListener\("visibilitychange",updateWorldAnimation\)/);
assert.match(source["world.js"],/window\.addEventListener\("wordmap:page",updateWorldAnimation\)/);
assert.match(source["world.js"],/cancelAnimationFrame\(animationFrameId\)/);
assert.match(source["sw.js"],/if\(req\.mode==="navigate"\)return caches\.match\("\.\/index\.html"\)/);
assert.match(source["sw.js"],/status:503/);
const css=source["world-theme.css"];
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length,"CSS braces are unbalanced");
for (const f of ["index.html","app.js","world.js","world-theme.css","sw.js","styles.css","data.js"]) assert.equal(read("public/"+f),source[f],f+" public copy differs from source");
const offline=source["WordMap-Offline.html"];
assert.ok(offline.includes("function refreshWordSelectors"),"offline HTML misses current app logic");
assert.ok(offline.includes("updateWorldAnimation"),"offline HTML misses 3D pause logic");
assert.ok(!/<script\s+src=/i.test(offline),"offline HTML still references external script files");
assert.ok(!/<link[^>]+href=["\x27]https?:/i.test(offline),"offline HTML contains external stylesheet links");
console.log("WordMap V5.1 static regression checks passed.");