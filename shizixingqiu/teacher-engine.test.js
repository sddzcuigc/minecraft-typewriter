import assert from "node:assert/strict";
globalThis.window=globalThis;
await import("./data.js");
await import("./teacher-engine.js");
const E=globalThis.SZX_TEACHER_ENGINE,rows=globalThis.HANZI_3500;
assert.equal(rows.length,3500,"字库应有3500条记录");
assert.deepEqual([E.parsePinyin("shān").initial,E.parsePinyin("shān").final,E.parsePinyin("shān").tone],["sh","an",1]);
assert.deepEqual([E.parsePinyin("shuǐ").initial,E.parsePinyin("shuǐ").final,E.parsePinyin("shuǐ").tone],["sh","ui",3]);
assert.equal(E.parsePinyin("lǜ").final,"v");
assert.equal(E.parsePinyin("guoguō"),null,"拼音字段异常值应被排除");
const lessonData={"山":["高山","高大的山。","远处有一座高山。","⛰️"]};
const sound=E.buildQuestion("山",rows,"char_to_pinyin","test-sound",lessonData);
assert.ok(sound,"单音字应能生成读音题");
assert.equal(sound.options.length,4);
assert.equal(new Set(sound.options.map(x=>x.value)).size,4);
assert.equal(sound.options.filter(x=>x.correct).length,1);
const word=E.buildQuestion("山",rows,"word_to_char","test-word",lessonData);
assert.ok(word,"有精选词语的汉字应能生成补字题");
assert.equal(word.maskedWord,"高□");
assert.equal(word.options.length,4);
assert.equal(new Set(word.options.map(x=>x.value)).size,4);
assert.equal(word.options.filter(x=>x.correct).length,1);
assert.equal(E.buildQuestion("行",rows,"char_to_pinyin","poly",lessonData),null,"多音字不得进入无语境读音题");
assert.equal(E.makeHint(sound,"shǎn").kind,"tone");
assert.equal(E.makeHint(sound,"sān").kind,"initial");
assert.equal(E.makeHint(sound,"shāng").kind,"final");
assert.ok(E.makeRepair(sound,lessonData).detail.includes("声母"));
const now=1000000000;
const first=E.makeProgress({}, {kind:"first",mistakes:0}, now);
assert.equal(first.level,1);assert.equal(first.nextAt,now+86400000);
const hinted=E.makeProgress({level:2,streak:2}, {kind:"hinted",mistakes:1}, now);
assert.equal(hinted.level,1);assert.equal(hinted.nextAt,now+86400000);
const repaired=E.makeProgress({}, {kind:"repaired",mistakes:2}, now);
assert.equal(repaired.level,0);assert.equal(repaired.nextAt,now+600000);
const plan=E.planLesson(rows,{水:{nextAt:now-1000,seen:1},山:{nextAt:now-2000,seen:1},行:{nextAt:now-3000,seen:1}},["人","行","口"],5,now);
assert.deepEqual(plan.chars.slice(0,2),["山","水"]);
assert.equal(plan.dueCount,2);
assert.ok(!plan.chars.includes("行"),"多音字在没有词境前不得自动出题");
const valid=E.validRowMap(rows);
assert.ok(valid.size>1000,"应保留足够多的可安全出题单音字");
console.log(JSON.stringify({ok:true,totalCharacters:rows.length,validatedSingleReadingCharacters:valid.size,checks:15},null,2));